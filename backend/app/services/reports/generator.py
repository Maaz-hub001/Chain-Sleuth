"""
Investigation Report Generator: produces validated structured JSON and Markdown representations.
"""
import uuid
from datetime import datetime
from typing import Dict, Any, List
from app.schemas.report import (
    ReportStructuredPayload,
    ReportFindingItem,
    ReportEvidenceItem
)
from app.services.reports.hasher import compute_report_hash


class ReportGenerator:
    @staticmethod
    def generate_report(
        investigation_id: str,
        target_identifier: str,
        target_type: str,
        chain_id: int,
        network_name: str,
        coverage_summary: Dict[str, Any],
        findings_data: List[Dict[str, Any]],
        evidence_data: List[Dict[str, Any]],
        intel_references: List[Dict[str, Any]],
        graph_summary: Dict[str, Any],
        ai_synthesis_notes: List[str]
    ) -> Dict[str, Any]:
        report_id = f"rep-{uuid.uuid4().hex[:12]}"
        now_iso = datetime.utcnow().isoformat() + "Z"

        # Format findings items
        finding_items = []
        for f in findings_data:
            finding_items.append(
                ReportFindingItem(
                    finding_id=f["id"],
                    detector_id=f.get("detector_id", "ANALYSIS"),
                    title=f["title"],
                    severity=f["severity"],
                    status=f["status"],
                    explanation=f["explanation"],
                    evidence_ids=f.get("evidence_ids") or [],
                    supporting_transactions=f.get("relevant_tx_hashes") or [],
                    supporting_sources=[r.get("title", "") for r in intel_references[:2]],
                    confidence=f.get("confidence", 0.8),
                    confidence_basis=f.get("confidence_basis", "Deterministic rule match"),
                    alternative_explanations=f.get("alternative_explanations") or [],
                    limitations=f.get("limitations") or "No off-chain ownership identity verified."
                )
            )

        # Format evidence items
        evidence_items = []
        for ev in evidence_data:
            evidence_items.append(
                ReportEvidenceItem(
                    evidence_id=ev["id"],
                    evidence_type=ev["evidence_type"],
                    title=ev["title"],
                    description=ev["description"],
                    raw_reference=ev["raw_reference"],
                    data_provenance=ev["data_provenance"]
                )
            )

        observed_facts = [
            f"Target {target_type} '{target_identifier}' examined on {network_name} (Chain ID: {chain_id}).",
            f"Constructed bounded transaction network of {graph_summary.get('total_nodes', 0)} nodes and {graph_summary.get('total_edges', 0)} directed transfer edges.",
            f"Data provider '{coverage_summary.get('provider', 'blockchain')}' reported coverage level: {coverage_summary.get('coverage_level', 'partial')}."
        ]
        if graph_summary.get("topological_cycles_detected", 0) > 0:
            observed_facts.append(f"Identified {graph_summary['topological_cycles_detected']} closed directed transaction loop(s).")
        if graph_summary.get("fan_out_hubs"):
            observed_facts.append(f"Identified {len(graph_summary['fan_out_hubs'])} fan-out disbursement hub(s).")

        counterevidence = [
            "Transfers on-chain prove movements of cryptographic tokens between addresses, but do not establish common beneficial ownership without off-chain attribution.",
            "High-frequency transfers or multi-recipient disbursement can be generated by benign smart contract routers, DeFi liquidity pools, and batch payroll contracts."
        ]

        limitations = [
            "Investigation scope is bounded to public on-chain transactions retrieved within configured horizon.",
            "Off-chain transactions (centralized exchange internal order book trades, private messaging, P2P agreements) are not visible on the public blockchain ledger.",
            "Attributions of entity names are derived from published security intelligence databases and require corroborating subpoena/KYC records for legal confirmation."
        ]

        recommended_next_steps = [
            "Request exchange compliance check for identified centralized exchange deposit hot wallet addresses.",
            "Monitor destination relay addresses for subsequent outbound transfers or bridge interactions.",
            "Anchor this report's canonical SHA-256 hash to the testnet InvestigationRegistry smart contract for tamper-evident record keeping."
        ]

        payload = ReportStructuredPayload(
            report_id=report_id,
            schema_version="1.0.0",
            investigation_id=investigation_id,
            generated_at=now_iso,
            chain_id=chain_id,
            network_name=network_name,
            target_type=target_type,
            target_identifier=target_identifier,
            investigation_scope={
                "max_depth": graph_summary.get("max_depth_explored", 2),
                "total_nodes": graph_summary.get("total_nodes", 0),
                "total_edges": graph_summary.get("total_edges", 0)
            },
            data_sources=[coverage_summary.get("provider", "rpc")],
            coverage_summary=coverage_summary,
            observed_facts=observed_facts,
            findings=finding_items,
            supporting_evidence=evidence_items,
            counterevidence=counterevidence,
            intelligence_references=intel_references,
            graph_paths=[
                {"type": "connected_components", "count": graph_summary.get("connected_components_count", 1)},
                {"type": "cycles", "count": graph_summary.get("topological_cycles_detected", 0)}
            ],
            unresolved_questions=[
                "Are intermediate relay addresses controlled by a single automated script or independent counterparties?",
                "Were private keys of intermediate addresses swept by an unconsented draining script?"
            ],
            limitations=limitations,
            recommended_next_steps=recommended_next_steps
        )

        payload_dict = payload.model_dump()
        report_hash, _ = compute_report_hash(payload_dict)

        # Generate Markdown
        markdown_text = ReportGenerator.render_markdown(payload_dict, report_hash)

        return {
            "report_id": report_id,
            "report_hash": report_hash,
            "content_json": payload_dict,
            "markdown_content": markdown_text
        }

    @staticmethod
    def render_markdown(payload: Dict[str, Any], report_hash: str) -> str:
        lines = []
        lines.append(f"# ChainSleuth Investigation Report: {payload.get('report_id')}")
        lines.append(f"**Generated:** {payload.get('generated_at')} | **Schema Version:** {payload.get('schema_version')}")
        lines.append(f"**Cryptographic Report Hash (SHA-256):** `{report_hash}`\n")
        lines.append("---")

        lines.append("## 1. Executive Summary & Target Scope")
        lines.append(f"- **Target Identifier:** `{payload.get('target_identifier')}` ({payload.get('target_type')})")
        lines.append(f"- **Blockchain Network:** {payload.get('network_name')} (Chain ID: {payload.get('chain_id')})")
        lines.append(f"- **Investigation ID:** `{payload.get('investigation_id')}`")
        lines.append(f"- **Data Provenance:** {', '.join(payload.get('data_sources', []))}")
        lines.append("")

        lines.append("## 2. Key Observed Facts")
        for fact in payload.get("observed_facts", []):
            lines.append(f"- {fact}")
        lines.append("")

        lines.append("## 3. Detailed Forensic Findings")
        for f in payload.get("findings", []):
            lines.append(f"### [{f.get('severity')}] {f.get('title')}")
            lines.append(f"**Status:** `{f.get('status')}` | **Confidence:** {int(f.get('confidence', 0)*100)}% ({f.get('confidence_basis')})")
            lines.append(f"\n{f.get('explanation')}\n")
            if f.get("supporting_transactions"):
                lines.append(f"**Referenced Transactions:** {', '.join([f'`{tx[:12]}...`' for tx in f.get('supporting_transactions', [])])}")
            lines.append(f"**Alternative Explanations:** {'; '.join(f.get('alternative_explanations', []))}")
            lines.append(f"**Counterevidence:** {f.get('counterevidence')}")
            lines.append("")

        lines.append("## 4. Supporting Threat Intelligence Citations")
        for ref in payload.get("intelligence_references", []):
            lines.append(f"- **{ref.get('title')}** ({ref.get('publisher')})")
            lines.append(f"  *Snippet:* \"{ref.get('snippet', '')[:160]}...\"")
            if ref.get("source_url"):
                lines.append(f"  *Source URL:* {ref.get('source_url')}")
        lines.append("")

        lines.append("## 5. Investigative Limitations & Notice")
        for lim in payload.get("limitations", []):
            lines.append(f"- {lim}")
        lines.append("\n> **Notice:** This document is an AI-assisted analytical record linking observations to verifiable on-chain evidence. Findings express algorithmic and evidentiary confidence rather than conclusive legal accusations.")
        return "\n".join(lines)
